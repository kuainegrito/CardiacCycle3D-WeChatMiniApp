// Copies the cardiac_cycle model engine, the 2D heart, the charts and the
// content from the web app into this mini program, so the mini program runs
// the website's own code. Engine files are copied unchanged; the two drawing
// modules get one import line that swaps the browser DOM for engine/mp-dom.js
// (and their import paths flattened); JSON becomes ES modules because mini
// programs cannot import .json.
// Run from this folder: node tools/sync-from-web.mjs [path/to/apps/cardiac_cycle]
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const web = process.argv[2] ?? "../../My_webpage/cycling-metabolism_simulator/apps/cardiac_cycle";
const ENGINE = [
  "waveforms.js",
  "valves.js",
  "conduction.js",
  "reduced-filling.js",
  "ventricular-timing.js",
  "clock.js",
  "atrial-targets.js",
  "valve-disease.js",
];
// Modules that touch the DOM: [source, target, globals they use].
const DOM_MODULES = [
  ["js/heart2d.js", "heart2d.js", "document"],
  ["js/engine/charts.js", "charts.js", "document, devicePixelRatio"],
];

await mkdir("engine", { recursive: true });
for (const file of ENGINE)
  await writeFile(join("engine", file), await readFile(join(web, "js/engine", file)));
for (const [source, target, globals] of DOM_MODULES) {
  const code = (await readFile(join(web, source), "utf8")).replaceAll('from "./engine/', 'from "./');
  await writeFile(
    join("engine", target),
    `// Copied by tools/sync-from-web.mjs from ${source}; only this line is added.\nimport { ${globals} } from "./mp-dom.js";\n` + code,
  );
}

const json = async (p) => JSON.parse(await readFile(join(web, p), "utf8"));
const header = "// Generated by tools/sync-from-web.mjs from the web app. Do not edit.\n";
const save = (name, value) => writeFile(join("data", name), header + "export default " + JSON.stringify(value) + ";\n");
await mkdir("data", { recursive: true });
await save("baseline.js", await json("content/cycle.baseline.json"));
const ids = await json("content/scenarios/index.json");
await save("scenarios.js", await Promise.all(ids.map((id) => json(`content/scenarios/${id}.json`))));
await save("atrial-volume.js", await json("content/atlas-atrial-volume.json"));
await save("labels.js", { en: await json("content/labels.en.json"), zh: await json("content/labels.zh.json") });
await save("heart-labels.js", { en: await json("assets/heart-labels.en.json"), zh: await json("assets/heart-labels.zh.json") });
console.log(`synced ${ENGINE.length + DOM_MODULES.length} engine files and 5 data modules`);
